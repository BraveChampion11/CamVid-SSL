from pathlib import Path
import random

import numpy as np
import torch
from torch.utils.data import Dataset
from PIL import Image, ImageEnhance


ROOT = Path(__file__).resolve().parents[1]


class CamVidUnlabeledDataset(Dataset):
    """
    Returns two geometrically aligned views of each unlabeled CamVid image.

    weak_view: teacher input
    strong_view: student input

    Strong augmentation is photometric only, so pseudo-label coordinates
    generated by the teacher remain aligned with the student image.
    """

    def __init__(
        self,
        labeled_manifest,
        image_size=(480, 360)
    ):
        self.root = ROOT / "data" / "CamVid"
        self.image_dir = self.root / "train"
        self.image_size = image_size

        if not self.image_dir.exists():
            raise FileNotFoundError(self.image_dir)

        manifest_path = Path(labeled_manifest)
        if not manifest_path.is_absolute():
            manifest_path = ROOT / manifest_path

        if not manifest_path.is_file():
            raise FileNotFoundError(manifest_path)

        with manifest_path.open("r", encoding="utf-8") as file:
            labeled_names = {
                line.strip()
                for line in file
                if line.strip()
            }

        all_names = {
            path.name for path in self.image_dir.glob("*.png")
        }

        missing = labeled_names - all_names
        if missing:
            raise FileNotFoundError(
                f"{len(missing)} labeled manifest images are missing. "
                f"Example: {next(iter(missing))}"
            )

        self.image_names = sorted(all_names - labeled_names)

        if not self.image_names:
            raise ValueError("No unlabeled training images were found.")

        self.mean = np.array(
            [0.485, 0.456, 0.406],
            dtype=np.float32
        )
        self.std = np.array(
            [0.229, 0.224, 0.225],
            dtype=np.float32
        )

    def __len__(self):
        return len(self.image_names)

    def _to_tensor(self, image):
        image_array = np.asarray(
            image,
            dtype=np.float32
        ) / 255.0

        image_array = (image_array - self.mean) / self.std

        return torch.from_numpy(
            image_array.transpose(2, 0, 1).copy()
        ).float()

    def _strong_color_augmentation(self, image):
        """Apply stronger photometric changes without geometric changes."""

        if random.random() < 0.8:
            image = ImageEnhance.Brightness(image).enhance(
                random.uniform(0.6, 1.4)
            )

        if random.random() < 0.8:
            image = ImageEnhance.Contrast(image).enhance(
                random.uniform(0.6, 1.4)
            )

        if random.random() < 0.8:
            image = ImageEnhance.Color(image).enhance(
                random.uniform(0.5, 1.5)
            )

        return image

    def __getitem__(self, index):
        image_name = self.image_names[index]
        image_path = self.image_dir / image_name

        image = Image.open(image_path).convert("RGB")

        image = image.resize(
            self.image_size,
            Image.Resampling.BILINEAR
        )

        # Both views receive exactly the same geometric transformation.
        if random.random() < 0.5:
            image = image.transpose(
                Image.Transpose.FLIP_LEFT_RIGHT
            )

        weak_view = image.copy()

        strong_view = self._strong_color_augmentation(
            image.copy()
        )

        weak_tensor = self._to_tensor(weak_view)
        strong_tensor = self._to_tensor(strong_view)

        return weak_tensor, strong_tensor, image_name